/** Every practice that keeps a scene: Heart's, Mind's, and Body's. */
export type SceneKey = MindTab | HeartTab | BodyTab;
export const SCENE_KEYS: readonly SceneKey[] = [...HEART_TABS, ...MIND_TABS, ...BODY_TABS];

/**
 * The scenes, one per practice on Heart, Mind and Body. Each is the practice
 * itself, made into a place: sitting tends a garden, reading builds a
 * library, gratitude raises a village, disputing a thought clears a river,
 * a brain dump drops ballast so the balloon can climb, and the five daily
 * prayers light a town in the snow.
 *
 * Each has sixty things that come into it, one more for each day you keep
 * the practice and one fewer for each scheduled day you miss (off-schedule
 * rest days hold steady). Stages appear in order and leave in reverse: the
 * newest is the first to go when a scheduled day is missed. See
 * lib/tending.ts for the rule.
 *
 * Names are written to read in a sentence: "Today brought {name}", "Sit
 * today to bring {name}", "Read today to keep {name}".
 */

export type SceneStage = { id: string; name: string };

export type Scene = {
  /** "The moonlit garden". */
  title: string;
  /** "garden", for "The garden is whole." */
  noun: string;
  /** What a whole scene says, when "The {noun} is whole." doesn't fit. */
  whole?: string;
  /** What's there with no days kept. */
  base: string;
  stages: readonly SceneStage[];
  /** The day's act, as an imperative: "Sit today". */
  act: string;
  /** Line shown on an off-schedule rest day when nothing is owed. */
  restLine?: string;
};

const stages = (list: [string, string][]): SceneStage[] => list.map(([id, name]) => ({ id, name }));

